#!/usr/bin/env node
// Deterministic JS→Go conformance fixtures for updates whose bytes end inside
// the delete set.
//
// yjs's readUpdateV2 integrates the structs, then readAndApplyDeleteSet
// deletes each range as soon as it has read the range's clock and length.
// When the bytes run out it throws, so the structs and every range read in
// full stay applied, the ranges it could not apply yet are not kept, and the
// transaction still emits its update. Each row is a real yjs update cut at one
// byte of its delete set (and the uncut update as a control), applied after a
// prefix, with the state and the update event yjs reaches. settled is the
// state after yjs's next retry of its parked structs and deletions (an empty
// update), and that retry's event: ygo drains its queue in the same apply,
// so that a peer given the part that landed ends where the document does.
//
// Determinism: pinned clientIDs, canonical JSON, trailing newline.
// Regenerated by `make fixtures`; CI's drift gate diffs the result.
const Y = require('yjs')
const fs = require('fs')
const path = require('path')
const assert = require('assert')

const outDir = path.join(__dirname, '..', 'crdt', 'testdata')
const hex = (u8) => Buffer.from(u8).toString('hex')

function peer (client) {
	const d = new Y.Doc({ gc: false })
	d.clientID = client
	return d
}

// transaction returns the V1 and V2 updates doc emits for fn.
function transaction (doc, fn) {
	let v1, v2
	const h1 = (u) => { v1 = u }
	const h2 = (u) => { v2 = u }
	doc.on('update', h1)
	doc.on('updateV2', h2)
	doc.transact(fn)
	doc.off('update', h1)
	doc.off('updateV2', h2)
	return { v1, v2 }
}

// deleteSetLength is the byte length of update's delete set, which ends it.
function deleteSetLength (update, v2) {
	const { ds } = v2 ? Y.decodeUpdateV2(update) : Y.decodeUpdate(update)
	const snap = Y.createSnapshot(ds, new Map())
	const enc = v2 ? Y.encodeSnapshotV2(snap) : Y.encodeSnapshot(snap)
	const tail = enc.slice(0, enc.length - 1) // drop the empty state vector
	assert.strictEqual(hex(update.slice(update.length - tail.length)), hex(tail), 'the delete set ends the update')
	return tail.length
}

function throws (fn) {
	try {
		fn()
		return false
	} catch (e) {
		return true
	}
}

// state is what the conformance test compares of d.
function state (d) {
	const sv = {}
	for (const [c, clock] of Y.decodeStateVector(Y.encodeStateVector(d))) sv[c] = clock
	const deleted = {}
	for (const [c, items] of Y.createDeleteSetFromStructStore(d.store).clients) {
		deleted[c] = items.map((it) => [it.clock, it.len])
	}
	return {
		text: d.getText('t').toString(),
		sv,
		deleted,
		pendingStructs: d.store.pendingStructs !== null,
		pendingDeletes: d.store.pendingDs !== null
	}
}

function outcome (prefix, update, v2, gc) {
	const d = new Y.Doc({ gc })
	d.clientID = 99
	Y.applyUpdate(d, prefix)
	let event = ''
	d.on('update', (u) => { event = hex(u) })
	let error = false
	try {
		if (v2) Y.applyUpdateV2(d, update)
		else Y.applyUpdate(d, update)
	} catch (e) {
		assert.strictEqual(e.message, 'Unexpected end of array')
		error = true
	}
	const result = { error, ...state(d), update: event }
	event = ''
	Y.applyUpdate(d, new Uint8Array([0, 0]))
	return {
		...result,
		// The update functions that read the delete set refuse the same cut.
		mergeThrows: throws(() => v2 ? Y.mergeUpdatesV2([update, Y.convertUpdateFormatV1ToV2(prefix)]) : Y.mergeUpdates([update, prefix])),
		diffThrows: throws(() => v2 ? Y.diffUpdateV2(update, new Uint8Array([0])) : Y.diffUpdate(update, new Uint8Array([0]))),
		convertThrows: throws(() => v2 ? Y.convertUpdateFormatV2ToV1(update) : Y.convertUpdateFormatV1ToV2(update)),
		settled: { ...state(d), update: event }
	}
}

const rows = []

// gc is the receiver's setting.
function scenario (name, prefix, { v1, v2 }, gc = true) {
	for (const [format, update] of [['v1', v1], ['v2', v2]]) {
		const isV2 = format === 'v2'
		const start = update.length - deleteSetLength(update, isV2)
		for (let cut = start; cut <= update.length; cut++) {
			rows.push({
				name: `${name}/${format}/${cut - start}`,
				format,
				gc,
				prefixV1: hex(prefix),
				update: hex(update.slice(0, cut)),
				expected: outcome(prefix, update.slice(0, cut), isV2, gc)
			})
		}
	}
}

// One struct, then deletions of two clients' items; client 300000 is a
// three-byte varint and comes first in the delete set, client 1 has two ranges.
{
	const a = peer(1)
	const b = peer(300000)
	a.getText('t').insert(0, 'hello world')
	Y.applyUpdate(b, Y.encodeStateAsUpdate(a))
	b.getText('t').insert(5, 'XYZ')
	Y.applyUpdate(a, Y.encodeStateAsUpdate(b))
	const prefix = Y.encodeStateAsUpdate(a)
	scenario('two-clients', prefix, transaction(a, () => {
		const t = a.getText('t')
		t.insert(t.length, 'Q')
		t.delete(12, 2)
		t.delete(5, 3)
		t.delete(0, 1)
	}))
}

// The struct parks (its origin 1:6 is missing); the delete set targets items
// the receiver has.
{
	const a = peer(1)
	a.getText('t').insert(0, 'abcdef')
	const prefix = Y.encodeStateAsUpdate(a)
	a.getText('t').insert(6, 'g')
	scenario('parked-struct', prefix, transaction(a, () => {
		const t = a.getText('t')
		t.insert(7, 'h')
		t.delete(1, 1)
		t.delete(3, 1)
	}))
}

// The first range targets client 300000, which the receiver lacks, so the
// whole update parks it; a cut after it drops it instead.
{
	const a = peer(1)
	const b = peer(300000)
	a.getText('t').insert(0, 'abcdef')
	const prefix = Y.encodeStateAsUpdate(a)
	Y.applyUpdate(b, prefix)
	b.getText('t').insert(0, 'XYZ')
	Y.applyUpdate(a, Y.encodeStateAsUpdate(b))
	scenario('missing-client', prefix, transaction(a, () => {
		const t = a.getText('t')
		t.insert(t.length, 'Q')
		t.delete(0, 1)
		t.delete(3, 1)
	}))
}

// The receiver holds a parked struct (e, after d) and a parked deletion of d.
// The update brings d, so a whole update lets both resolve; a cut one leaves
// them parked, since yjs throws before it retries them. The receiver keeps
// deleted content, so the update that resolves them writes d as a string.
{
	const a = peer(1)
	a.getText('t').insert(0, 'abc')
	const base = Y.encodeStateAsUpdate(a)
	const d = transaction(a, () => a.getText('t').insert(3, 'd')).v1
	const e = transaction(a, () => {
		const t = a.getText('t')
		t.insert(4, 'e')
		t.delete(3, 1)
	}).v1
	const del = transaction(a, () => a.getText('t').delete(0, 1)).v1
	const update = Y.mergeUpdates([d, del])
	scenario('earlier-parked', Y.mergeUpdates([base, e]), { v1: update, v2: Y.convertUpdateFormatV1ToV2(update) }, false)
}

// Hand-built updates with no structs whose delete set claims more clients or
// ranges than it holds (2^20 + 1, above any per-update item limit) and then
// ends; yjs reads and applies ranges until the bytes run out.
{
	const varuint = (n) => {
		const out = []
		while (n > 0x7f) {
			out.push(0x80 | (n & 0x7f))
			n = Math.floor(n / 128)
		}
		out.push(n)
		return out
	}
	const many = (1 << 20) + 1
	// groups: [client, claimed range count, [[clock, len], ...]]
	const crafted = (name, clients, groups) => {
		const v1 = [0, ...varuint(clients)]
		// The V2 columns and struct count of a yjs update with no structs.
		const v2 = [...Y.convertUpdateFormatV1ToV2(Uint8Array.from([0, 0])).slice(0, -1), ...varuint(clients)]
		for (const [client, count, ranges] of groups) {
			v1.push(...varuint(client), ...varuint(count))
			v2.push(...varuint(client), ...varuint(count))
			let cur = 0
			for (const [clock, len] of ranges) {
				v1.push(...varuint(clock), ...varuint(len))
				v2.push(...varuint(clock - cur), ...varuint(len - 1))
				cur = clock + len
			}
		}
		const a = peer(1)
		a.getText('t').insert(0, 'abcdef')
		const prefix = Y.encodeStateAsUpdate(a)
		for (const [format, update] of [['v1', Uint8Array.from(v1)], ['v2', Uint8Array.from(v2)]]) {
			rows.push({ name: `${name}/${format}`, format, gc: true, prefixV1: hex(prefix), update: hex(update), expected: outcome(prefix, update, format === 'v2', true) })
		}
	}
	crafted('many-ranges', 1, [[1, many, [[0, 1], [2, 1]]]])
	crafted('many-clients', many, [[1, 1, [[0, 1]]]])
	crafted('many-ranges-second-group', 2, [[1, 1, [[0, 1]]], [1, many, [[4, 1]]]])
}

const file = path.join(outDir, 'truncated_ds_yjs_fixtures.json')
fs.writeFileSync(file, JSON.stringify(rows, null, 2) + '\n')
console.log(`wrote crdt/testdata/truncated_ds_yjs_fixtures.json (${rows.length} rows)`)
