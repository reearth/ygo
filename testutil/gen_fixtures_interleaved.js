#!/usr/bin/env node
// Deterministic JS→Go conformance fixtures for INTERLEAVED multi-peer
// histories: several peers edit one document concurrently and sync only some
// of their transactions straight away, so each client's structs depend on
// other clients' structs. Loading, merging and applying such a history out of
// order resolves long cross-client dependency chains.
//
// Each row holds every transaction's update (V1 and V2), yjs's encoded full
// state, a shuffled delivery order, and what yjs ends with after receiving
// everything: the JSON of each root and the live and deleted sets.
//
// Determinism: pinned clientIDs, seeded PRNG, canonical JSON, trailing
// newline. Regenerated by `make fixtures`; CI's drift gate diffs the result.
const Y = require('yjs')
const fs = require('fs')
const path = require('path')

const outDir = path.join(__dirname, '..', 'crdt', 'testdata')
const hex = (u8) => Buffer.from(u8).toString('hex')

function rng (seed) {
	let s = seed >>> 0
	return () => {
		s = (s + 0x6d2b79f5) >>> 0
		let t = s
		t = Math.imul(t ^ (t >>> 15), t | 1)
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296
	}
}

function idSet (doc, deleted) {
	const out = []
	for (const client of [...doc.store.clients.keys()].sort((a, b) => a - b)) {
		for (const s of doc.store.clients.get(client)) {
			if (s.deleted !== deleted) continue
			const last = out[out.length - 1]
			if (last && last[0] === client && last[1] + last[2] === s.id.clock) {
				last[2] += s.length
			} else {
				out.push([client, s.id.clock, s.length])
			}
		}
	}
	return out
}

function snapshot (doc) {
	return {
		text: doc.getText('text').toDelta(),
		array: doc.getArray('array').toJSON(),
		map: Object.fromEntries(Object.entries(doc.getMap('map').toJSON()).sort(([a], [b]) => (a < b ? -1 : 1))),
		live: idSet(doc, false),
		deleted: idSet(doc, true)
	}
}

// edit makes one random transaction on doc.
function edit (doc, rand, step) {
	const text = doc.getText('text')
	const array = doc.getArray('array')
	const map = doc.getMap('map')
	const r = rand()
	doc.transact(() => {
		if (r < 0.45) {
			const at = Math.floor(rand() * (text.length + 1))
			text.insert(at, `${doc.clientID % 100}.${step} `)
		} else if (r < 0.55 && text.length > 0) {
			const at = Math.floor(rand() * text.length)
			text.delete(at, Math.min(1 + Math.floor(rand() * 4), text.length - at))
		} else if (r < 0.6 && text.length > 0) {
			const at = Math.floor(rand() * text.length)
			text.format(at, Math.min(3, text.length - at), { bold: rand() < 0.7 ? true : null })
		} else if (r < 0.75) {
			const at = Math.floor(rand() * (array.length + 1))
			array.insert(at, [step, `s${step}`])
		} else if (r < 0.8 && array.length > 0) {
			array.delete(Math.floor(rand() * array.length), 1)
		} else if (r < 0.95) {
			map.set(`k${Math.floor(rand() * 6)}`, step)
		} else {
			map.delete(`k${Math.floor(rand() * 6)}`)
		}
	})
}

// typed is the turn-taking shape: peers append to one text in turn, each
// seeing every earlier step.
function typed (doc, step) {
	const text = doc.getText('text')
	doc.transact(() => text.insert(text.length, ` ${doc.clientID % 100}-${step}`))
}

function session (name, seed, peers, steps, shape) {
	const rand = rng(seed)
	const docs = []
	for (let i = 0; i < peers; i++) {
		const doc = new Y.Doc()
		doc.clientID = 1000 + seed * 10 + i
		docs.push(doc)
	}
	const updates = []
	// inbox[i] holds update indices peer i has not received yet.
	const inbox = docs.map(() => [])
	for (let step = 0; step < steps; step++) {
		const p = shape === 'typed' ? step % peers : Math.floor(rand() * peers)
		const doc = docs[p]
		const before = Y.encodeStateVector(doc)
		if (shape === 'typed') typed(doc, step)
		else edit(doc, rand, step)
		const v1 = Y.encodeStateAsUpdate(doc, before)
		updates.push({ v1, v2: Y.encodeStateAsUpdateV2(doc, before) })
		const index = updates.length - 1
		for (let i = 0; i < peers; i++) {
			if (i !== p) inbox[i].push(index)
		}
		for (let i = 0; i < peers; i++) {
			if (shape === 'typed' || rand() < 0.35) {
				for (const u of inbox[i]) Y.applyUpdate(docs[i], updates[u].v1)
				inbox[i] = []
			}
		}
	}
	const all = new Y.Doc()
	for (const u of updates) Y.applyUpdate(all, u.v1)
	const order = updates.map((_, i) => i)
	for (let i = order.length - 1; i > 0; i--) {
		const j = Math.floor(rand() * (i + 1))
		;[order[i], order[j]] = [order[j], order[i]]
	}
	const shuffled = new Y.Doc()
	for (const i of order) Y.applyUpdate(shuffled, updates[i].v1)
	const expected = snapshot(all)
	if (JSON.stringify(snapshot(shuffled)) !== JSON.stringify(expected)) {
		throw new Error(`${name}: yjs did not converge on the shuffled order`)
	}
	return {
		name,
		v1: { state: hex(Y.encodeStateAsUpdate(all)), updates: updates.map((u) => hex(u.v1)) },
		v2: { state: hex(Y.encodeStateAsUpdateV2(all)), updates: updates.map((u) => hex(u.v2)) },
		order,
		expected
	}
}

const rows = []
for (let seed = 1; seed <= 10; seed++) {
	rows.push(session(`random/${seed}`, seed, 3 + (seed % 3), 60, 'random'))
}
rows.push(session('typed/5x400', 11, 5, 400, 'typed'))
rows.push(session('typed/3x300', 12, 3, 300, 'typed'))

const file = path.join(outDir, 'interleaved_yjs_fixtures.json')
fs.writeFileSync(file, JSON.stringify(rows, null, 2) + '\n')
console.log(`wrote crdt/testdata/interleaved_yjs_fixtures.json (${rows.length} sessions)`)
