#!/usr/bin/env node
// Deterministic JS→Go conformance fixtures for updates that carry SEVERAL
// wire groups for the same client.
//
// yjs never encodes such an update, but any peer can send one. yjs's decoder
// (readClientsStructRefs) stores each group with clientRefs.set(client, ...),
// so only the LAST group for a client survives and earlier groups are dropped
// without being integrated. These fixtures pin that behaviour: each row is an
// update built by splicing single-client groups cut from real yjs updates,
// plus the state yjs reaches after applying it.
//
// V2 rows are produced by yjs's own convertUpdateFormatV1ToV2. Its writer
// merges ADJACENT groups for one client, so V2 is only emitted for rows whose
// repeated groups are separated by another client.
//
// Determinism: pinned clientIDs, canonical JSON, trailing newline.
// Regenerated by `make fixtures`; CI's drift gate diffs the result.
const Y = require('yjs')
const fs = require('fs')
const path = require('path')
const assert = require('assert')

const outDir = path.join(__dirname, '..', 'crdt', 'testdata')
const hex = (u8) => Buffer.from(u8).toString('hex')

function varuint (n) {
	const out = []
	while (n > 0x7f) {
		out.push(0x80 | (n & 0x7f))
		n = Math.floor(n / 128)
	}
	out.push(n)
	return out
}

// history records full-state snapshots of one or more pinned peers.
function peer (client) {
	const d = new Y.Doc()
	d.clientID = client
	return d
}

function snapshot (doc) {
	const d = new Y.Doc()
	Y.applyUpdate(d, Y.encodeStateAsUpdate(doc))
	return d
}

// group cuts client's structs from clock `from` to its end out of doc. The
// update is [1][group][delete set]; an update against the doc's own state
// vector is [0][delete set], which gives the delete set's length.
function group (doc, client, from) {
	const sv = Y.decodeStateVector(Y.encodeStateVector(doc))
	sv.set(client, from)
	const u = Y.encodeStateAsUpdate(doc, Y.encodeStateVector(sv))
	const ds = Y.encodeStateAsUpdate(doc, Y.encodeStateVector(doc))
	assert.strictEqual(u[0], 1, 'exactly one group')
	assert.strictEqual(ds[0], 0, 'no groups')
	return u.slice(1, u.length - (ds.length - 1))
}

function splice (groups) {
	const parts = [Uint8Array.from(varuint(groups.length)), ...groups, Uint8Array.from([0])]
	return Buffer.concat(parts.map((p) => Buffer.from(p)))
}

// coverage merges each client's struct ranges, so duplicates or overlaps
// would show up as extra or non-monotonic ranges.
function coverage (doc) {
	const out = {}
	for (const [client, structs] of doc.store.clients) {
		const ranges = []
		for (const s of structs) {
			const last = ranges[ranges.length - 1]
			if (last && last[1] === s.id.clock) last[1] += s.length
			else ranges.push([s.id.clock, s.id.clock + s.length])
		}
		out[client] = ranges
	}
	return out
}

function outcome (prefix, update, apply) {
	const d = new Y.Doc()
	if (prefix) apply(d, prefix)
	apply(d, update)
	const sv = {}
	for (const [c, clock] of Y.decodeStateVector(Y.encodeStateVector(d))) sv[c] = clock
	return {
		text: d.getText('t').toString(),
		other: d.getText('u').toString(),
		map: d.getMap('m').toJSON(),
		sv,
		coverage: coverage(d),
		pending: d.store.pendingStructs !== null
	}
}

function row (name, groups, { prefix = null, v2 = true } = {}) {
	const v1 = splice(groups)
	const want = outcome(prefix, v1, Y.applyUpdate)
	const r = { name, v1: hex(v1), prefixV1: prefix ? hex(prefix) : '', expected: want }
	if (v2) {
		const u2 = Y.convertUpdateFormatV1ToV2(v1)
		const p2 = prefix ? Y.convertUpdateFormatV1ToV2(prefix) : null
		assert.deepStrictEqual(outcome(p2, u2, Y.applyUpdateV2), want, name + ': V2 must match V1')
		r.v2 = hex(u2)
		r.prefixV2 = p2 ? hex(p2) : ''
	}
	return r
}

// Client 9 types into t one character per transaction; yjs merges the
// characters into one struct, so each snapshot is one struct of its length.
const nine = peer(9)
const nineAt = []
for (const ch of 'abc') {
	nine.getText('t').insert(nine.getText('t').length, ch)
	nineAt.push(snapshot(nine))
}
const [a, ab, abc] = nineAt

// Client 1 writes into a separate root, so its group never depends on 9.
const one = peer(1)
one.getText('u').insert(0, 'xy')

// Client 2 inserts after client 9's "b", so it depends on clock 9:1.
const two = snapshot(abc)
two.clientID = 2
two.getText('t').insert(2, 'Z')

// Client 9 deletes a nested map; yjs garbage-collects its children into GC
// structs, so a group cut after the delete carries GC structs over the clocks
// a group cut before it supplies.
const gcPeer = peer(9)
gcPeer.transact(() => {
	const n = new Y.Map()
	gcPeer.getMap('m').set('n', n)
	n.set('k', 'v')
	n.set('j', 'w')
})
const gcBefore = snapshot(gcPeer)
gcPeer.getMap('m').delete('n')

const rows = [
	// The reported shape: [0,3) then a group repeating clock 0, back to back.
	row('adjacent_overlap_shorter_last', [group(abc, 9, 0), group(a, 9, 0)], { v2: false }),
	row('overlap_shorter_last', [group(abc, 9, 0), group(one, 1, 0), group(a, 9, 0)]),
	row('overlap_longer_last', [group(a, 9, 0), group(one, 1, 0), group(abc, 9, 0)]),
	// The earlier group is NOT a superset: dropping it leaves a clock gap.
	row('continuation_dropped', [group(ab, 9, 0), group(one, 1, 0), group(abc, 9, 2)]),
	// Another client depends on a clock only the dropped group carried.
	row('dependency_on_dropped', [group(abc, 9, 0), group(two, 2, 0), group(a, 9, 0)]),
	row('three_groups', [group(a, 9, 0), group(one, 1, 0), group(abc, 9, 0), group(two, 2, 0), group(ab, 9, 0)]),
	// The receiver already holds "a"; only the last group is consulted.
	row('prefix_known', [group(abc, 9, 0), group(one, 1, 0), group(a, 9, 0)], { prefix: Y.encodeStateAsUpdate(a) }),
	// A dropped group's GC structs must not delete what the last group supplies.
	row('dropped_gc_group', [group(gcPeer, 9, 0), group(one, 1, 0), group(gcBefore, 9, 0)])
]

const file = path.join(outDir, 'dupgroups_yjs_fixtures.json')
fs.writeFileSync(file, JSON.stringify(rows, null, 2) + '\n')
console.log(`wrote crdt/testdata/dupgroups_yjs_fixtures.json (${rows.length} scenarios)`)
