// Deterministic JS→Go conformance fixtures for YText formatting around inserts,
// embeds and deletions.
//
// `single` rows replay an op script on one doc and record Yjs's V1/V2 state and
// toDelta. `multi` rows replay a script across peers joined by explicit syncs
// and record every peer's delta after each step plus its final V1 state, so a
// receiving peer's post-transaction format cleanup is visible at the
// step it happens.
//
// Op script (shared with the Go test):
//   ins   {i, s, a?}   YText.insert; no `a` means no attributes argument
//   emb   {i, v, a?}   YText.insertEmbed
//   fmt   {i, n, a}    YText.format
//   del   {i, n}       YText.delete
//   delta {d}          YText.applyDelta
//   sync  {from, to, v2?}  apply from's diff against to's state vector
// Attribute objects list keys sorted: Yjs orders markers by key insertion,
// ygo by sorted key.
//
// Regenerated by `make fixtures`; CI's drift gate diffs the result.
const Y = require('yjs')
