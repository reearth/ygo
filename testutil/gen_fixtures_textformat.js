const hex = (u8) => Buffer.from(u8).toString('hex')

// Yjs's insertText adds a null for every current attribute to the object it
// is given, so each call gets a copy and the recorded script stays as written.
function apply (t, op) {
	const o = structuredClone(op)
	switch (o.k) {
		case 'ins': return o.a === undefined ? t.insert(o.i, o.s) : t.insert(o.i, o.s, o.a)
		case 'emb': return o.a === undefined ? t.insertEmbed(o.i, o.v) : t.insertEmbed(o.i, o.v, o.a)
		case 'fmt': return t.format(o.i, o.n, o.a)
		case 'del': return t.delete(o.i, o.n)
		case 'delta': return t.applyDelta(o.d)
	}
	throw new Error('unknown op ' + o.k)
}

function single (name, ops) {
	const d = new Y.Doc()
	d.clientID = 9
	const t = d.getText('t')
	for (const o of ops) apply(t, o)
	return { name, ops, v1: hex(Y.encodeStateAsUpdate(d)), v2: hex(Y.encodeStateAsUpdateV2(d)), delta: t.toDelta() }
}

function multi (name, clients, ops) {
	const docs = {}
	for (const [p, c] of Object.entries(clients)) {
		docs[p] = new Y.Doc()
		docs[p].clientID = c
	}
	const peers = Object.keys(clients).sort()
	const trace = []
	for (const o of ops) {
		if (o.k === 'sync') {
			const from = docs[o.from]
			const to = docs[o.to]
			if (o.v2) Y.applyUpdateV2(to, Y.encodeStateAsUpdateV2(from, Y.encodeStateVector(to)))
			else Y.applyUpdate(to, Y.encodeStateAsUpdate(from, Y.encodeStateVector(to)))
		} else {
			apply(docs[o.p].getText('t'), o)
		}
		trace.push(peers.map((p) => docs[p].getText('t').toDelta()))
	}
	const final = peers.map((p) => ({ peer: p, v1: hex(Y.encodeStateAsUpdate(docs[p])) }))
	return { name, clients, ops, trace, final }
}

