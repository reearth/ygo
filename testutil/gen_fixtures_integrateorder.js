#!/usr/bin/env node
// Deterministic JS→Go conformance fixtures for the ORDER in which an applied
// update integrates its structs. Yjs's integrateStructs takes clients highest
// first and, when a struct needs another client's struct from the same
// update, integrates that client's structs first; parked structs are retried
// in the same order when a later update fills the gap.
//
// Each row is one random multi-peer session (text, map, a one-key nested
// map, array; GC off so deleted content keeps its type) delivered to a fresh
// receiver five ways: full state, full state with client groups written ascending,
// every transaction's update in a shuffled order, merged runs of updates in
// a shuffled order, and periodic syncs from random peers. For each applied
// update the row records what yjs did: the string items in integration order
// and the clients of the transaction's delete set in insertion order.
//
// Determinism: pinned clientIDs, seeded PRNG, canonical JSON, trailing
// newline. Regenerated by `make fixtures`; CI's drift gate diffs the result.
const Y = require('yjs')
const encoding = require('lib0/encoding')
const fs = require('fs')
const path = require('path')

const outDir = path.join(__dirname, '..', 'crdt', 'testdata')
const hex = (u8) => Buffer.from(u8).toString('hex')

function rng (seed) {
	let s = seed >>> 0
	return () => {
		s = (s + 0x6d2b79f5) >>> 0
		let t = s
		t = Math.imul(t ^ (t >>> 15), t | 1)
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296
	}
}

// trace collects integrated string items while an update applies.
let trace = null
const integrate = Y.Item.prototype.integrate
Y.Item.prototype.integrate = function (transaction, offset) {
	const id = [this.id.client, this.id.clock + offset]
	const isString = this.content.constructor === Y.ContentString
	integrate.call(this, transaction, offset)
	if (trace !== null && isString && this.parent !== null) trace.push(id)
}

// apply applies u to doc and returns what the transaction did.
function apply (doc, u, v2) {
	trace = []
	let ds = []
	const listen = (tr) => { ds = [...tr.deleteSet.clients.keys()] }
	doc.on('afterTransaction', listen)
	if (v2) Y.applyUpdateV2(doc, u)
	else Y.applyUpdate(doc, u)
	doc.off('afterTransaction', listen)
	const out = { strings: trace, ds }
	trace = null
	return out
}

// ascending re-encodes a V1 update with its client groups in ascending order.
function ascending (u) {
	const { structs, ds } = Y.decodeUpdate(u)
	const groups = new Map()
	for (const s of structs) {
		if (!groups.has(s.id.client)) groups.set(s.id.client, [])
		groups.get(s.id.client).push(s)
	}
	const enc = new Y.UpdateEncoderV1()
	const clients = [...groups.keys()].sort((a, b) => a - b)
	encoding.writeVarUint(enc.restEncoder, clients.length)
	for (const client of clients) {
		const group = groups.get(client)
		encoding.writeVarUint(enc.restEncoder, group.length)
		enc.writeClient(client)
		encoding.writeVarUint(enc.restEncoder, group[0].id.clock)
		for (const s of group) s.write(enc, 0)
	}
	encoding.writeVarUint(enc.restEncoder, ds.clients.size)
	for (const [client, ranges] of ds.clients) {
		encoding.writeVarUint(enc.restEncoder, client)
		encoding.writeVarUint(enc.restEncoder, ranges.length)
		for (const r of ranges) {
			encoding.writeVarUint(enc.restEncoder, r.clock)
			encoding.writeVarUint(enc.restEncoder, r.len)
		}
	}
	return enc.toUint8Array()
}

// edit makes one random transaction on doc.
function edit (doc, rand, step) {
	const text = doc.getText('text')
	const map = doc.getMap('map')
	const array = doc.getArray('array')
	const r = rand()
	doc.transact(() => {
		if (r < 0.3) {
			text.insert(Math.floor(rand() * (text.length + 1)), `${doc.clientID % 100}.${step} `)
		} else if (r < 0.4 && text.length > 0) {
			const at = Math.floor(rand() * text.length)
			text.delete(at, Math.min(1 + Math.floor(rand() * 4), text.length - at))
		} else if (r < 0.55) {
			map.set(`k${Math.floor(rand() * 4)}`, step)
		} else if (r < 0.65) {
			const nested = new Y.Map()
			nested.set('v', `${doc.clientID % 100}.${step}`)
			map.set(`n${Math.floor(rand() * 2)}`, nested)
		} else if (r < 0.8) {
			const nested = map.get(`n${Math.floor(rand() * 2)}`)
			if (nested instanceof Y.Map) nested.set('v', `${doc.clientID % 100}.${step}`)
			else text.insert(0, `${doc.clientID % 100}.${step}`)
		} else if (r < 0.85) {
			map.delete(`k${Math.floor(rand() * 4)}`)
		} else if (r < 0.95) {
			array.insert(Math.floor(rand() * (array.length + 1)), [`${doc.clientID % 100}.${step}`])
		} else if (array.length > 0) {
			array.delete(Math.floor(rand() * array.length), 1)
		}
	})
}

function shuffle (rand, xs) {
	for (let i = xs.length - 1; i > 0; i--) {
		const j = Math.floor(rand() * (i + 1))
		;[xs[i], xs[j]] = [xs[j], xs[i]]
	}
	return xs
}

// deliver applies V1 updates to fresh receivers (V1, and the same updates as
// V2) and returns the updates with what yjs did. Both formats must agree.
function deliver (name, updates) {
	const v1 = new Y.Doc({ gc: false })
	v1.clientID = 1
	const v2 = new Y.Doc({ gc: false })
	v2.clientID = 1
	return updates.map((u, i) => {
		const want = apply(v1, u, false)
		const got = apply(v2, Y.convertUpdateFormatV1ToV2(u), true)
		if (JSON.stringify(got) !== JSON.stringify(want)) {
			throw new Error(`${name}: update ${i} integrates differently as V2`)
		}
		return { v1: hex(u), v2: hex(Y.convertUpdateFormatV1ToV2(u)), ...want }
	})
}

function session (seed, peers, steps) {
	const name = `random/${seed}`
	const rand = rng(seed)
	const docs = []
	for (let i = 0; i < peers; i++) {
		const doc = new Y.Doc({ gc: false })
		// Client IDs out of peer order, so the highest client is not the first peer.
		doc.clientID = 10 + ((i * 7 + seed) % 23)
		while (docs.some((d) => d.clientID === doc.clientID)) doc.clientID++
		docs.push(doc)
	}
	const updates = []
	const inbox = docs.map(() => [])
	// The sync receiver pulls a peer's whole difference now and then.
	const receiver = new Y.Doc({ gc: false })
	receiver.clientID = 1
	const syncs = []
	for (let step = 0; step < steps; step++) {
		const p = Math.floor(rand() * peers)
		const before = Y.encodeStateVector(docs[p])
		edit(docs[p], rand, step)
		updates.push(Y.encodeStateAsUpdate(docs[p], before))
		for (let i = 0; i < peers; i++) {
			if (i !== p) inbox[i].push(updates.length - 1)
		}
		for (let i = 0; i < peers; i++) {
			if (rand() < 0.3) {
				for (const u of inbox[i]) Y.applyUpdate(docs[i], updates[u])
				inbox[i] = []
			}
		}
		if (rand() < 0.25) {
			const u = Y.encodeStateAsUpdate(docs[Math.floor(rand() * peers)], Y.encodeStateVector(receiver))
			Y.applyUpdate(receiver, u)
			syncs.push(u)
		}
	}
	const all = new Y.Doc({ gc: false })
	for (const u of updates) Y.applyUpdate(all, u)
	const state = Y.encodeStateAsUpdate(all)
	const runs = []
	for (let i = 0; i < updates.length;) {
		const n = 1 + Math.floor(rand() * 6)
		runs.push(Y.mergeUpdates(updates.slice(i, i + n)))
		i += n
	}
	return {
		name,
		deliveries: {
			state: deliver(`${name} state`, [state]),
			ascending: deliver(`${name} ascending`, [ascending(state)]),
			shuffled: deliver(`${name} shuffled`, shuffle(rand, updates.slice())),
			merged: deliver(`${name} merged`, shuffle(rand, runs)),
			syncs: deliver(`${name} syncs`, syncs)
		}
	}
}

const rows = []
for (let seed = 1; seed <= 16; seed++) {
	rows.push(session(seed, 3 + (seed % 3), 40))
}

const file = path.join(outDir, 'integrateorder_yjs_fixtures.json')
fs.writeFileSync(file, JSON.stringify(rows) + '\n')
console.log(`wrote crdt/testdata/integrateorder_yjs_fixtures.json (${rows.length} sessions)`)
