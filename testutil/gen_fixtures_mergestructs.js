#!/usr/bin/env node
// Deterministic JS→Go conformance fixtures for the struct merge yjs runs at
// the end of every transaction (cleanupTransactions): deleted structs merge
// with their neighbours, and the structs a transaction adds merge with the
// struct on their left, also one from an earlier transaction.
//
// Each row replays a session, one transaction per op, and holds yjs's full
// state (V1 and V2). An "apply" row instead applies each update of a session
// to a second document, so the merge runs on received updates.
//
// Determinism: pinned clientIDs, seeded PRNG, canonical JSON, trailing
// newline. Regenerated by `make fixtures`; CI's drift gate diffs the result.
const Y = require('yjs')
const fs = require('fs')
const path = require('path')

const outDir = path.join(__dirname, '..', 'crdt', 'testdata')
const hex = (u8) => Buffer.from(u8).toString('hex')

function mulberry32 (a) {
	return function () {
		a |= 0; a = a + 0x6D2B79F5 | 0
		let t = Math.imul(a ^ a >>> 15, 1 | a)
		t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t
		return ((t ^ t >>> 14) >>> 0) / 4294967296
	}
}

// editingSession is a typing session with backspaces, word deletes, map
// overwrites, array inserts and deletes, and transactions that delete two
// text ranges, the later one first.
function editingSession (seed, n) {
	const rnd = mulberry32(seed)
	const ri = (k) => Math.floor(rnd() * k)
	const letters = 'abcdefghijklmnopqrstuvwxyz '
	let textLen = 0
	let arrLen = 0
	let cursor = 0
	const ops = []
	for (let i = 0; i < n; i++) {
		const r = rnd()
		if (r < 0.60) {
			if (rnd() < 0.05) cursor = ri(textLen + 1)
			cursor = Math.min(cursor, textLen)
			ops.push(['ins', cursor, letters[ri(letters.length)]])
			textLen++; cursor++
		} else if (r < 0.85) {
			if (textLen === 0) continue
			const k = rnd() < 0.8 ? 1 : Math.min(textLen, 1 + ri(6))
			let pos = Math.min(cursor, textLen) - k
			if (pos < 0) pos = 0
			const len = Math.min(k, textLen - pos)
			if (len === 0) continue
			ops.push(['del', pos, len])
			textLen -= len; cursor = pos
		} else if (r < 0.92) {
			ops.push(['mset', 'k' + ri(20), ri(1000)])
		} else if (r < 0.97) {
			ops.push(['ains', ri(arrLen + 1), ri(1000)])
			arrLen++
		} else if (r < 0.99) {
			if (arrLen === 0) continue
			ops.push(['adel', ri(arrLen), 1])
			arrLen--
		} else {
			if (textLen < 10) continue
			const a = ri(textLen - 6)
			const b = a + 3 + ri(textLen - a - 4)
			ops.push(['del2', a, b])
			textLen -= 2
			cursor = Math.min(cursor, textLen)
		}
	}
	ops.push(['ins', textLen, 'x'])
	return ops
}

function apply (doc, op) {
	const text = doc.getText('t')
	const arr = doc.getArray('a')
	doc.transact(() => {
		switch (op[0]) {
			case 'ins': text.insert(op[1], op[2]); break
			case 'del': text.delete(op[1], op[2]); break
			case 'del2': text.delete(op[2], 1); text.delete(op[1], 1); break
			case 'mset': doc.getMap('m').set(op[1], op[2]); break
			case 'ains': arr.insert(op[1], [op[2]]); break
			case 'adel': arr.delete(op[1], op[2]); break
			case 'ains3': for (let k = 0; k < 3; k++) arr.insert(op[1] + k, [op[2] + k]); break
			case 'ainsm': for (const [p, v] of op[1]) arr.insert(p, [v]); break
			default: throw new Error('unknown op ' + op[0])
		}
	})
}

function state (doc) {
	return { v1: hex(Y.encodeStateAsUpdate(doc)), v2: hex(Y.encodeStateAsUpdateV2(doc)) }
}

// sessions holds each op list once; rows name theirs.
const sessions = {
	typing: Array.from('mergeme', (c, i) => ['ins', i, c]),
	backspace: [['ins', 0, 'abcdef'], ['del', 5, 1], ['del', 4, 1], ['del', 3, 1], ['del', 2, 1]],
	pushes: [1, 2, 3, 4, 5].map((v, i) => ['ains', i, v]),
	pushes3: [['ains3', 0, 1], ['ains3', 3, 4]],
	// two runs in one transaction, the second before the first
	runs2: [['ainsm', [[0, 1], [1, 2], [0, 3], [1, 4]]]],
	editing: editingSession(42, 5000)
}

// replay applies a session to a fresh document (client 1), one transaction
// per op.
function replay (name, gc, session) {
	const doc = new Y.Doc({ gc })
	doc.clientID = 1
	for (const op of sessions[session]) apply(doc, op)
	return { name, gc, session, ...state(doc) }
}

// received applies each update of the first n ops of a session to a second
// document.
function received (name, gc, session, n) {
	const src = new Y.Doc({ gc })
	src.clientID = 1
	const updates = []
	src.on('update', (u) => updates.push(hex(u)))
	for (const op of sessions[session].slice(0, n)) apply(src, op)
	const dst = new Y.Doc({ gc })
	dst.clientID = 2
	for (const u of updates) Y.applyUpdate(dst, Buffer.from(u, 'hex'))
	return { name, gc, updates, ...state(dst) }
}

// gcStructs applies two updates that each carry one GC struct of client 5,
// the second continuing the first.
function gcStructs (name) {
	const updates = ['010105000002' + '00', '010105020003' + '00']
	const dst = new Y.Doc()
	dst.clientID = 2
	for (const u of updates) Y.applyUpdate(dst, Buffer.from(u, 'hex'))
	return { name, gc: true, updates, ...state(dst) }
}

const rows = [
	replay('typing', true, 'typing'),
	replay('backspace', true, 'backspace'),
	replay('backspace/nogc', false, 'backspace'),
	replay('array-push', true, 'pushes'),
	replay('array-push/one-transaction', true, 'pushes3'),
	replay('array-push/two-runs', true, 'runs2'),
	received('typing/received', true, 'typing'),
	received('backspace/received', true, 'backspace'),
	gcStructs('gc-structs/received'),
	replay('editing/5000', true, 'editing'),
	replay('editing/5000/nogc', false, 'editing'),
	received('editing/1000/received', true, 'editing', 1000)
]

const file = path.join(outDir, 'mergestructs_yjs_fixtures.json')
fs.writeFileSync(file, JSON.stringify({ sessions, rows }) + '\n')
console.log(`wrote crdt/testdata/mergestructs_yjs_fixtures.json (${rows.length} rows)`)
