#!/usr/bin/env node
// Deterministic JS→Go conformance fixtures for delete sets that cover items
// already deleted. Yjs readAndApplyDeleteSet splits a struct at a range end
// only while it is live, and splits the range end only when its loop reaches
// that struct, after the deletions before it. Each scenario records the
// updates the document emits at each step and its final state.
//
// Garbage collection is off in every scenario, so deleted text keeps its
// characters and a split through a surrogate pair would show in the state.
//
// Determinism: pinned clientID, fixed steps, canonical JSON, trailing newline.
// Regenerated by `make fixtures`; CI's drift gate diffs the result.
const Y = require('yjs')
const fs = require('fs')
const path = require('path')

const CLIENT_ID = 1
const outDir = path.join(__dirname, '..', 'crdt', 'testdata')
const hex = (u8) => Buffer.from(u8).toString('hex')

// deleteSet returns a V1 update with no structs and the given [clock, len]
// delete ranges of CLIENT_ID (every value fits in one varint byte): 0 clients
// of structs, 1 client, the client, the number of ranges, then each range.
const deleteSet = (...ranges) => Uint8Array.from([0, 1, CLIENT_ID, ranges.length, ...ranges.flat()])

// scenario runs setup, then each step, recording what the doc emits per step.
function scenario (name, description, setup, steps) {
  const doc = new Y.Doc({ gc: false })
  doc.clientID = CLIENT_ID
  const ctx = setup(doc)
  let emitted = []
  doc.on('update', (u) => { emitted.push(hex(u)) })
  const out = []
  for (const [label, run] of steps) {
    emitted = []
    run(doc, ctx)
    out.push({ label, updates: emitted })
  }
  return { name, description, steps: out, state: hex(Y.encodeStateAsUpdate(doc)), text: ctx.text.toString() }
}

// deletedRun types text into "t" under an UndoManager, then deletes it all.
function deletedRun (s) {
  return (doc) => {
    const text = doc.getText('t')
    const um = new Y.UndoManager(text)
    doc.transact(() => { text.insert(0, s) })
    um.stopCapturing()
    doc.transact(() => { text.delete(0, text.length) })
    um.stopCapturing()
    return { text, um }
  }
}

const fixtures = [
  scenario(
    'redelete_redone_run',
    'Undo restores a deleted run as a redone copy; a delete set inside the deleted original then leaves it whole; redo and undo follow.',
    deletedRun('abcdefgh'),
    [
      ['undo', (doc, c) => { c.um.undo() }],
      ['redelete', (doc) => { Y.applyUpdate(doc, deleteSet([2, 3]), 'remote') }],
      ['redo', (doc, c) => { c.um.redo() }],
      ['undo again', (doc, c) => { c.um.undo() }]
    ]
  ),
  scenario(
    'redelete_start_inside_supplementary',
    'A delete set starting inside a deleted emoji (clocks 1-2) leaves it whole, so undo and redo restore and delete the emoji itself.',
    deletedRun('x\u{1F600}y'),
    [
      ['redelete', (doc) => { Y.applyUpdate(doc, deleteSet([2, 1]), 'remote') }],
      ['undo', (doc, c) => { c.um.undo() }],
      ['redo', (doc, c) => { c.um.redo() }]
    ]
  ),
  scenario(
    'redelete_end_inside_supplementary',
    'A delete set ending inside a deleted emoji (clocks 1-2) leaves it whole, so undo and redo restore and delete the emoji itself.',
    deletedRun('x\u{1F600}y'),
    [
      ['redelete', (doc) => { Y.applyUpdate(doc, deleteSet([1, 1]), 'remote') }],
      ['undo', (doc, c) => { c.um.undo() }],
      ['redo', (doc, c) => { c.um.redo() }]
    ]
  ),
  scenario(
    'cascade_into_supplementary',
    'A delete set from a nested text\'s container into its emoji deletes the container first; the cascade deletes the text, so its range end does not split the emoji.',
    (doc) => {
      const arr = doc.getArray('a')
      const text = new Y.Text()
      doc.transact(() => { arr.insert(0, [text]) })
      doc.transact(() => { text.insert(0, 'x\u{1F600}y') })
      return { text }
    },
    [
      ['delete', (doc) => { Y.applyUpdate(doc, deleteSet([0, 3]), 'remote') }]
    ]
  ),
  scenario(
    'two_ranges',
    'One delete set with two ranges: the first ends inside the live run "abcdefgh" (clocks 0-7), which splits; the second lies inside the deleted run at clocks 8-10, which stays whole.',
    (doc) => {
      const text = doc.getText('t')
      doc.transact(() => { text.insert(0, 'abcdefgh') })
      doc.transact(() => { text.insert(8, 'XYZ') })
      doc.transact(() => { text.delete(8, 3) })
      return { text }
    },
    [
      ['delete', (doc) => { Y.applyUpdate(doc, deleteSet([2, 2], [9, 1]), 'remote') }]
    ]
  )
]

const file = path.join(outDir, 'redelete_yjs_fixtures.json')
fs.writeFileSync(file, JSON.stringify({ fixtures }, null, 2) + '\n')
console.log(`wrote crdt/testdata/redelete_yjs_fixtures.json (${fixtures.length} scenarios)`)
